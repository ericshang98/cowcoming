 await page.getByRole('button',{name:'进化设置',exact:true}).click();
 assert.equal(await page.getByLabel('每几轮评估一次').inputValue(),'10');
 assert.equal(await page.getByLabel('评估模型',{exact:true}).inputValue(),'test-evaluator');
 await page.screenshot({path:'output/evolution-qa/evolution-settings.png',fullPage:true});
